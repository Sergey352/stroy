//
// КУДА ВСТАВИТЬ: в конструкторе формы — кнопка «Скрипт» в настройках формы
// (не через API, скрипты форм программно не создаются — как и остальная
// структура формы). Этот файл в репозитории — просто хранилище копии кода
// для истории версий, сам Pyrus его из git не подхватывает, вставлять
// нужно руками, как и src/index.js на Cloudflare.
//
// ЧТО ДЕЛАЕТ:
//   1. Автоподстановка: как только в строке таблицы «Позиции заявки»
//      выбирается элемент справочника «Номенклатура» (id=44), скрипт сразу же
//      (ещё до отправки заявки, в браузере/приложении пользователя) читает
//      остальные колонки ЭТОЙ строки справочника «Смета» и подставляет их
//      в соседние ячейки той же строки таблицы: Название, Ед. изм.,
//      Кол-во по смете, Остаток, Цена. Пользователю вручную остаётся
//      заполнить только «Заказанное количество».
//   2. Предупреждение о превышении: если «Заказанное количество» больше,
//      чем «Остаток» (сколько ещё осталось по смете на эту позицию) —
//      показывается предупреждение под полем. errorMessage не блокирует
//      сохранение (canSave: true) — это именно предупреждение, а не
//      жёсткий запрет (если нужно наоборот запрещать сохранять — уберите
//      canSave: true).
//
// ПРОВЕРИТЬ НА РЕАЛЬНОЙ ФОРМЕ ПОСЛЕ ВСТАВКИ:
//   Работа onChange/setValue/validate внутри табличного поля подтверждена
//   и официальной справкой Pyrus (https://pyrus.com/ru/help/scripts/tables
//   — сессия 2026-08-18), и личным опытом настройки другой формы
//   пользователем — сама возможность не под вопросом. Но зона
//   срабатывания (что именно попадает в state.changes построчно) стоит
//   всё равно перепроверить на нашей конкретной таблице: создать тестовую
//   заявку, добавить строку в таблицу, выбрать «Номенклатура» и
//   убедиться, что соседние ячейки заполнились именно в ЭТОЙ строке.

// --- 1. Автоподстановка данных из справочника «Смета» ---
//
// Поля формы (первый аргумент onChange, аргумент setValue/validate) —
// ссылаемся ТОЛЬКО по коду (code), не по названию. Так же, как во всех
// остальных скриптах проекта (pyrus_client.py и т.д.) — код не меняется,
// даже если название поля потом переименуют в конструкторе, а название
// сломало бы скрипт молча.
//
// Коды колонок таблицы «Позиции заявки» (проставлены в конструкторе,
// сессия 2026-08-18):
//   item_catalog     — Номенклатура (catalog-поле, справочник «Смета»)
//   item_name        — Название
//   item_unit        — Ед. изм.
//   item_qty_ordered — Заказанное количество (вводит пользователь)
//   item_qty_budget  — Кол-во по смете
//   item_remainder   — Остаток
//   item_price       — Цена
//
// А вот item?.columns['Наименование'] и т.д. ниже — это НЕ код поля формы,
// а имя КОЛОНКИ СПРАВОЧНИКА «Смета» (у справочников кодов нет, только у
// полей формы) — должно точно совпадать с CATALOG_HEADERS в
// smeta_catalog_import.py.

form.onChange(['item_catalog'])
  .setValue('item_name', state => {
    const [item] = state.changes;
    return item?.columns['Наименование'];
  });

form.onChange(['item_catalog'])
  .setValue('item_unit', state => {
    const [item] = state.changes;
    return item?.columns['Ед. изм.'];
  });

// item_qty_budget/item_remainder/item_price — поля типа «число»/«деньги»,
// а значения колонок справочника всегда приходят СТРОКОЙ (например "11"
// или "836103"). Для текстовых полей (item_name/item_unit) строка
// подставляется напрямую и работает («Текст» по формату полей Pyrus
// принимает и объект {text: "..."}, и просто строку). А «Число»/«Деньги»
// по официальному формату (https://pyrus.com/ru/help/scripts/field-value-formats)
// принимают {value: 42} или просто число 42 — но НЕ строку "42" — поэтому
// нужно явно привести к числу через Number(). toNumber() ниже
// дополнительно защищается от пустой/нечисловой строки (вернёт undefined
// вместо NaN, чтобы не затирать поле мусором).

function toNumber(raw) {
  if (raw === undefined || raw === null || raw === '') return undefined;
  const n = Number(raw);
  return Number.isNaN(n) ? undefined : n;
}

form.onChange(['item_catalog'])
  .setValue('item_qty_budget', state => {
    const [item] = state.changes;
    return toNumber(item?.columns['Кол-во по смете']);
  });

form.onChange(['item_catalog'])
  .setValue('item_remainder', state => {
    const [item] = state.changes;
    return toNumber(item?.columns['Остаток']);
  });

form.onChange(['item_catalog'])
  .setValue('item_price', state => {
    const [item] = state.changes;
    return toNumber(item?.columns['Цена']);
  });

// --- 2. Предупреждение при превышении остатка ---
// Срабатывает при изменении «Заказанное количество» ИЛИ «Остаток»
// (например, «Остаток» мог только что подставиться автоподстановкой выше —
// нужно перепроверить условие и в этом случае тоже).

form.onChange(['item_qty_ordered', 'item_remainder'])
  .validate('item_qty_ordered', state => {
    const [ordered, remaining] = state.changes;
    if (ordered?.value == null || remaining?.value == null) {
      return; // одно из полей ещё не заполнено — проверять нечего
    }
    if (ordered.value > remaining.value) {
      return {
        errorMessage: `Превышен остаток по смете: заказано ${ordered.value}, доступно ${remaining.value}`,
        canSave: true, // предупреждение, не жёсткий запрет — заявку всё равно можно отправить
      };
    }
  });

// --- 3. Список «Объект» — только объекты, где текущий пользователь прораб ---
//
// Задача (сессия 2026-08-19, по внешнему ТЗ подрядчика): прораб не должен
// физически видеть в списке чужие объекты — раньше ограничивался только
// маршрут (кто согласовывает), а сам список объектов был общий для всех.
//
// МЕХАНИЗМ (подтверждён документацией https://pyrus.com/ru/help/scripts/filtering):
//   form.onChange(['Поле'], true).setFilterAsync('Поле', ...) — второй
//   аргумент true у onChange означает «сработать сразу при открытии формы»,
//   а не только когда пользователь САМ поменяет это поле — иначе фильтр
//   применился бы только после того, как прораб уже случайно открыл бы
//   список со всеми объектами один раз. Поле фильтрует само себя — это
//   тоже задокументированный, а не придуманный паттерн (пример в справке —
//   про поле «Регион»).
//
// НЕ ПОДТВЕРЖДЕНО ДОКУМЕНТАЦИЕЙ (проверить на реальной форме после вставки):
//   Официальная справка Pyrus описывает state.commenter («пользователь,
//   который сейчас заполняет форму») только словами, БЕЗ примера кода и
//   БЕЗ описания точной структуры объекта — как достать числовой id
//   человека, неизвестно наверняка (предполагаем person_id по аналогии с
//   другим примером в той же справке про фильтрацию по колонке-участнику).
//   Поэтому ниже — проверка НЕСКОЛЬКИХ вероятных вариантов подряд
//   (getPersonId), а не одного — чтобы сработало, даже если Pyrus вернёт
//   не совсем то поле, которое мы предположили. Если после вставки список
//   всё равно не фильтруется — значит ни один из вариантов не подошёл,
//   тогда нужно смотреть в консоли браузера (console.log(state.commenter)
//   можно временно добавить сюда же), какая структура на самом деле.
//
// БЕЗОПАСНЫЙ ОТКАТ: если для текущего пользователя не нашлось ни одного
// объекта, где он указан прорабом (например, это снабженец, руководитель
// или тестовый администратор, а не прораб конкретного объекта) — фильтр
// возвращает null, то есть показывает ПОЛНЫЙ список, а не пустой. Иначе
// снабженец/руководитель, у которых в принципе может быть повод открыть
// эту форму, увидели бы пустой список и не смогли бы вообще ничего выбрать.

const objectsCatalogPromise = form.getCatalog('Объекты стройки');

function getPersonId(person) {
  if (!person) return undefined;
  return person.person_id ?? person.Id ?? person.id ?? undefined;
}

form.onChange(['Object'], true)
  .setFilterAsync('Object', async state => {
    const myId = getPersonId(state.commenter);
    if (myId === undefined) return null; // не смогли определить пользователя — не фильтруем

    const items = await objectsCatalogPromise;
    const allowedNames = items
      .filter(item => getPersonId(item.columns['Прораб']) == myId) // == специально: id может прийти числом или строкой
      .map(item => item.columns['Объект']);

    if (allowedNames.length === 0) return null; // не нашли ни одного объекта — не фильтруем (см. пояснение выше)
    return { values: allowedNames };
  });
